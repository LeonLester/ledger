import { extraLoad, fitOf, repTable, resFit, trueRes, weightFor } from "../src/lib/mech.ts";
let fails = 0;
const ok = (c, m) => { if (!c) { fails++; console.log("FAIL", m); } else console.log("ok  ", m); };
const near = (a, b, e = 0.05) => Math.abs(a - b) <= e;
const lp = fitOf({ ma: { dxVer: 71, dx: 100 } });
ok(near(trueRes(lp, 100), 71), "leg press 45 degrees, 100 kg feels like 71");
ok(near(weightFor(lp, 71), 100), "71 kg true resistance needs 100 kg");
ok(fitOf({}) === null && fitOf({ ma: { dxVer: 0, dx: 5 } }) === null, "no data gives no fit");
const lev = fitOf({ lever: { loadArm: 200, userArm: 100, start: 0, end: 0.0001, offset: 0, armMass: 0, armCom: 0, path: "arc", pull: 90 } });
ok(near(lev.a, 2, 0.001) && near(lev.b, 0, 0.001), "lever with equal-ish angles: arm ratio 2");
const lev2 = fitOf({ lever: { loadArm: 100, userArm: 100, start: 0, end: 0.0001, offset: 0, armMass: 10, armCom: 100, path: "arc", pull: 90 } });
ok(near(trueRes(lev2, 50), 60, 0.01) && near(weightFor(lev2, 60), 50, 0.01), "arm mass adds a constant");
ok(extraLoad({ base: 40, bwf: 0.25, bw: 80 }) === 60 && extraLoad({}) === 0, "tare weight and bodyweight share add up");
const xl = extraLoad({ base: 40 });
ok(near(trueRes(lp, 100, xl), 99.4, 0.01) && near(weightFor(lp, 99.4, xl), 100, 0.05), "leg press with a 40 kg sled: (100 + 40) x 0.71");
const assist = resFit(undefined, extraLoad({ bwf: 1, bw: 80 }));
ok(near(trueRes(assist, -30, 80), 50) && near(weightFor(assist, 50, 80), -30), "assisted pull-up: 80 kg bodyweight with -30 assistance is 50");
ok(resFit(undefined, 0) === null, "no extras, no column");
const e1 = (w, r) => (r <= 1 ? w : w * (1 + r / 30)), at = (e, n) => (n <= 1 ? e : e / (1 + n / 30));
const t1 = repTable({ weight: 100, reps: 5 }, { fit: null, extra: 0, inc: 2.5, e1, at });
ok(near(t1.e1, 116.67, 0.01) && t1.rows[0].weight === 117.5 && t1.rows[4].weight === 100, "rep table: 100 x 5 round trips, 1RM about 117.5");
ok(t1.rows[4].trust === "high" && t1.rows[7].trust === "mid" && t1.rows[14].trust === "low", "trust fades with distance from the tested reps");
const pu = repTable({ weight: 0, reps: 8 }, { fit: resFit(undefined, 80), extra: 80, inc: 1, e1, at });
ok(near(pu.e1, 101.33, 0.01) && pu.rows[0].weight === 21, "pull-up at 80 kg bodyweight for 8: 1RM needs +21 added");
console.log(fails ? `${fails} failed` : "all passed"); process.exit(fails ? 1 : 0);
